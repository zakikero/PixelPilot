"""pipecat-quickstart - Pipecat Voice Agent

This bot uses a cascade pipeline: Speech-to-Text → LLM → Text-to-Speech

Generated by Pipecat CLI

Local services:
- Whisper (Speech-to-Text)
- Ollama (LLM)
- Kokoro (Text-to-Speech)

Run the bot using::

    uv run bot.py
"""

import argparse
import asyncio
import os
import sys
from pathlib import Path

import yaml
from dotenv import load_dotenv
from loguru import logger
from pipecat.audio.filters.rnnoise_filter import RNNoiseFilter
from pipecat.audio.vad.silero import SileroVADAnalyzer
from pipecat.observers.loggers.llm_log_observer import LLMLogObserver
from pipecat.observers.loggers.transcription_log_observer import (
    TranscriptionLogObserver,
)
from pipecat.pipeline.pipeline import Pipeline
from pipecat.pipeline.worker import (
    PipelineParams,
    PipelineWorker,
    ProcessorUnusablePolicy,
)
from pipecat.processors.aggregators.llm_context import LLMContext
from pipecat.processors.aggregators.llm_response_universal import (
    LLMContextAggregatorPair,
    LLMUserAggregatorParams,
)
from pipecat.processors.audio.vad_processor import VADProcessor
from pipecat.runner.types import RunnerArguments, SmallWebRTCRunnerArguments
from pipecat.runner.utils import create_transport
from pipecat.services.kokoro.tts import KokoroTTSService
from pipecat.services.ollama.llm import OLLamaLLMService
from pipecat.services.whisper.stt import WhisperSTTService
from pipecat.transports.base_transport import BaseTransport, TransportParams
from pipecat.turns.user_start import WakePhraseUserTurnStartStrategy
from pipecat.turns.user_turn_strategies import (
    UserTurnStrategies,
    default_user_turn_start_strategies,
)
from pipecat.workers.runner import WorkerRunner

load_dotenv(override=True)

CONFIG_PATH = Path(__file__).with_name("config.yaml")
with CONFIG_PATH.open() as config_file:
    CONFIG = yaml.safe_load(config_file)

logger.remove(0)
logger.add(sys.stderr, level=os.getenv("LOG_LEVEL", CONFIG["logging"]["level"]).upper())


async def run_bot(transport: BaseTransport, runner_args: RunnerArguments) -> None:
    """Run an independent conversation using the supplied audio transport."""

    logger.info("Starting bot")

    vad_processor = VADProcessor(vad_analyzer=SileroVADAnalyzer())

    stt = WhisperSTTService(
        settings=WhisperSTTService.Settings(
            model=CONFIG["whisper"]["model"],
            language=CONFIG["whisper"]["language"],
        ),
        device=CONFIG["whisper"]["device"],
        compute_type=CONFIG["whisper"]["compute_type"],
    )

    llm = OLLamaLLMService(
        base_url=CONFIG["ollama"]["host"],
        settings=OLLamaLLMService.Settings(
            model=CONFIG["ollama"]["model"],
            system_instruction=CONFIG["ollama"]["system_instruction"],
            temperature=CONFIG["ollama"]["temperature"],
        ),
    )

    # tts = PiperTTSService(
    #     model_name=CONFIG["piper"]["model_name"],
    #     voice_id=CONFIG["piper"]["voice_id"],
    # )

    tts = KokoroTTSService(
        speed=CONFIG["kokoro"]["speed"],
        settings=KokoroTTSService.Settings(
            voice=CONFIG["kokoro"]["voice"],
            language=CONFIG["kokoro"]["language"],
        ),
    )

    wake_strategy = None
    user_turn_start_strategies = default_user_turn_start_strategies()
    if CONFIG.get("wake", {}).get("enabled", False):
        wake_strategy = WakePhraseUserTurnStartStrategy(
            phrases=CONFIG["wake"]["phrases"],
            timeout=CONFIG["wake"]["timeout"],
        )
        user_turn_start_strategies.insert(0, wake_strategy)

    context = LLMContext()
    user_aggregator, assistant_aggregator = LLMContextAggregatorPair(
        context,
        user_params=LLMUserAggregatorParams(
            vad_analyzer=SileroVADAnalyzer(),
            user_turn_strategies=UserTurnStrategies(
                start=user_turn_start_strategies,
            ),
        ),
    )

    pipeline = Pipeline(
        [
            transport.input(),
            vad_processor,
            stt,
            user_aggregator,
            llm,
            tts,
            transport.output(),
            assistant_aggregator,
        ]
    )

    worker = PipelineWorker(
        pipeline,
        params=PipelineParams(
            # enable_metrics=True,
            # enable_usage_metrics=True,
        ),
        observers=[
            TranscriptionLogObserver(),
            LLMLogObserver(),
        ],
        idle_timeout_secs=runner_args.pipeline_idle_timeout_secs,
        processor_unusable_policy=ProcessorUnusablePolicy.END,
    )

    if wake_strategy is not None:

        @wake_strategy.event_handler("on_wake_phrase_detected")
        async def on_wake_phrase_detected(strategy, phrase):
            print(f"Wake phrase detected: {phrase}")

        @wake_strategy.event_handler("on_wake_phrase_timeout")
        async def on_wake_phrase_timeout(strategy):
            print("Timeout — returning to idle")

    @worker.event_handler("on_pipeline_started")
    async def on_pipeline_started(worker, frame):
        logger.info("Pipeline is running and ready!")

    @worker.event_handler("on_pipeline_finished")
    async def on_pipeline_finished(worker, frame):
        logger.info("Pipeline has stopped")

    @worker.event_handler("on_pipeline_error")
    async def on_pipeline_error(worker, frame):
        logger.error(f"Pipeline error occurred: {frame}")

    @worker.event_handler("on_idle_timeout")
    async def on_idle_timeout(worker):
        logger.info("No activity detected — pipeline is idle")

    runner = WorkerRunner(
        handle_sigint=runner_args.handle_sigint,
        handle_sigterm=runner_args.handle_sigterm,
    )

    if isinstance(runner_args, SmallWebRTCRunnerArguments):

        @transport.event_handler("on_client_connected")
        async def on_client_connected(transport, client):
            logger.info("WebRTC client connected — ready for speech")

        @transport.event_handler("on_client_disconnected")
        async def on_client_disconnected(transport, client):
            logger.info("WebRTC client disconnected — stopping this conversation")
            await runner.cancel()

    # whisker = WhiskerServer()
    # worker.add_observer(whisker.create_observer(worker))
    # await runner.add_workers(whisker, worker)
    await runner.add_workers(worker)
    await runner.run()


async def bot(runner_args: RunnerArguments) -> None:
    """Create a SmallWebRTC session for Pipecat's development runner."""
    if not isinstance(runner_args, SmallWebRTCRunnerArguments):
        raise ValueError("PixelPilot's server supports SmallWebRTC; use -t webrtc.")

    try:
        transport = await create_transport(
            runner_args,
            {
                "webrtc": lambda: TransportParams(
                    audio_in_enabled=True,
                    audio_out_enabled=True,
                ),
            },
        )
        await run_bot(transport, runner_args)
    finally:
        # Also release the peer if model initialization fails before the runner starts.
        await runner_args.webrtc_connection.disconnect()


async def run_local_bot() -> None:
    """Run the shared pipeline using the host microphone and speakers."""
    from pipecat.transports.local.audio import LocalAudioTransport, LocalAudioTransportParams

    transport = LocalAudioTransport(
        LocalAudioTransportParams(
            audio_in_enabled=True,
            audio_in_filter=RNNoiseFilter(),
            audio_out_enabled=True,
            input_device_index=CONFIG["audio"]["input_device_index"],
            output_device_index=CONFIG["audio"]["output_device_index"],
        )
    )
    runner_args = RunnerArguments()
    runner_args.handle_sigint = True
    runner_args.handle_sigterm = True
    await run_bot(transport, runner_args)


def main() -> None:
    """Select local audio or forward WebRTC options to Pipecat's runner."""
    parser = argparse.ArgumentParser(
        description="PixelPilot voice bot",
        epilog=(
            "WebRTC also accepts Pipecat runner options such as --host, --port, "
            "--ice-servers and --allowed-origins."
        ),
    )
    parser.add_argument(
        "-t",
        "--transport",
        choices=["webrtc", "local"],
        default="webrtc",
        help="Audio transport (default: webrtc)",
    )
    args, runner_options = parser.parse_known_args()
    if args.transport == "local":
        if runner_options:
            parser.error(f"Local audio does not accept runner options: {' '.join(runner_options)}")
        asyncio.run(run_local_bot())
        return

    from pipecat.runner.run import main as runner_main

    # Pipecat parses sys.argv itself. Restrict its server to the selected transport.
    original_argv = sys.argv
    try:
        sys.argv = [sys.argv[0], "-t", "webrtc", *runner_options]
        runner_main()
    finally:
        sys.argv = original_argv


if __name__ == "__main__":
    main()
